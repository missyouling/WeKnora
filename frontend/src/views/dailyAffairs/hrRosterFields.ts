/**
 * 把模板导入值 / 后端旧值统一归一到四态。
 * `工作性质=退休返聘` 优先（任务明确要求自动识别）。
 */
export function normalizeRosterStatus(v: unknown, workNature?: unknown): RosterStatusView {
  if (String(workNature ?? '').trim() === '退休返聘') return '退休返聘'
  const s = String(v ?? '').trim()
  if (!s) return '全部'
  if (/^(正式|在职|active|employed)$/i.test(s)) return '在职'
  if (/^(试用|试用期|probation)$/i.test(s)) return '试用期'
  if (/^(已离职|待离职|离职|resigned)$/i.test(s)) return '离职'
  if (s === '退休返聘') return '退休返聘'
  if (s === '在职' || s === '试用期' || s === '离职') return s as RosterStatusView
  return '全部'
}

/** 字段是否为日期/时间类（用于导入清洗和单元格格式化）。 */
export function isRosterDateField(name: string): boolean {
  return /日期|时间|有效期/.test(String(name || ''))
}
