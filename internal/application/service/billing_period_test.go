package service

import "testing"

// 账单周期归一化：所有日期范围 / 中文年月 / 单日，一律收敛成 YYYY-MM。
//
// 为什么必须归一：
//
//	账单原文的周期写法极不统一（"2026年8月1日~2026年8月31日"、"2026.08.01-2026.08.31"、
//	"2026-09-01"），直接上屏会把列宽撑爆并显示成 "2026-09-0..."。
//	业务上"账单月份"本身就是月粒度，日精度没有意义，因此统一到 YYYY-MM。
func TestNormalizeBillingPeriod(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		{"中文范围", "2026年8月1日~2026年8月31日", "2026-08"},
		{"中文范围带空格", "2026年8月1日 - 2026年8月31日", "2026-08"},
		{"ISO 范围", "2026-08-01~2026-08-31", "2026-08"},
		{"ISO 范围至", "2026-08-01至2026-08-31", "2026-08"},
		{"点分范围", "2026.08.01-2026.08.31", "2026-08"},
		{"斜杠范围", "2026/08/01 - 2026/08/31", "2026-08"},
		{"单日 ISO", "2026-09-01", "2026-09"},
		{"中文年月", "2026年9月", "2026-09"},
		{"中文年月带日", "2026年8月1日", "2026-08"},
		{"紧凑六位", "202608", "2026-08"},
		{"已归一", "2026-08", "2026-08"},
		{"点分年月", "2026.08", "2026-08"},
		{"斜杠年月", "2026/8", "2026-08"},
		{"单位数月补零", "2026-8-1", "2026-08"},
		{"带账单周期前缀", "账单周期：2026年8月1日~2026年8月31日", "2026-08"},
		{"带抄表周期前缀", "抄表周期 2026-09-01 - 2026-09-30", "2026-09"},
		{"空串", "", ""},
		{"纯空白", "   ", ""},
		{"无法解析", "本月", ""},
		{"月份越界不猜", "2026年13月", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := NormalizeBillingPeriod(c.in); got != c.want {
				t.Fatalf("NormalizeBillingPeriod(%q) = %q, want %q", c.in, got, c.want)
			}
		})
	}
}

// 归一化必须幂等：迁移脚本会重跑，重复归一不能把 2026-08 变坏。
func TestNormalizeBillingPeriodIdempotent(t *testing.T) {
	for _, in := range []string{"2026-08", "2026年8月1日~2026年8月31日", "202608"} {
		once := NormalizeBillingPeriod(in)
		twice := NormalizeBillingPeriod(once)
		if once != twice {
			t.Fatalf("幂等性破坏：%q → %q → %q", in, once, twice)
		}
	}
}
