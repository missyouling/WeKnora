// 车队归档类（车辆档案 / 司机档案 / 维保记录）的提取规则注册表。
//
// 为什么单独一个文件而不是往 BusinessFieldCatalogs() 里再塞 9 份完整目录：
// 这三类证照的字段集来自 `fleet_categories.subs`（用户在「设置 → 字段定义」里
// 可以增删改），如果这里再硬编码一份 35 字段的目录，两边一定会漂移 ——
// 用户在界面加了「核定载质量」，提取规则里却没有它，模型永远提不出来。
//
// 因此这里只做**富化**：字段清单由调用方从 subs 传入，本文件负责给已知字段补
// Desc / Rule / Regex 与整份 Prompt。未知字段也能提取（有名字就有 schema），
// 只是没有专门规则。

// FleetArchiveCertTypes 归档类 9 个证照类型（与分类 name 逐字一致）。
var FleetArchiveCertTypes = []string{
	"道路运输经营许可证", "道路运输证", "车辆登记证书", "保险单", "行驶证",
	"驾驶证", "从业资格证",
	"一般维修", "合格证",
}

// IsFleetArchiveScope 是否车队归档类 scope（这三者走证照提取，与记录型台账不同）。
func IsFleetArchiveScope(scope string) bool {
	switch strings.TrimSpace(scope) {
	case "vehicle", "driver", "maintain":
		return true
	}
	return false
}

