// FleetArchiveFieldRule 返回某证照类型下某字段的富化规则（找不到返回零值）。
func FleetArchiveFieldRule(certType, fieldName string) fleetFieldRule {
	ct := strings.TrimSpace(certType)
	name := strings.TrimSpace(fieldName)
	if m, ok := fleetCertFieldRules[ct]; ok {
		if r, ok := m[name]; ok {
			return r
		}
	}
	// 别名（真实 subs 里的叫法与标准叫法不一致时）
	if m, ok := fleetCertFieldRuleExtras[ct]; ok {
		if r, ok := m[name]; ok {
			return r
		}
	}
	if r, ok := fleetCommonFieldRules[name]; ok {
		return r
	}
	if r, ok := fleetCommonFieldRuleExtras[name]; ok {
		return r
	}
	return fleetFieldRule{}
}

// FleetArchiveFieldsFromSubs 把分类 subs 展开成提取字段配置，并按证照类型补规则。
//
// 字段清单一律以 subs 为权威源（名字即 data key），本函数只补 Desc/Rule/Regex；
// 停用的字段（enabled=false）不参与提取。
func FleetArchiveFieldsFromSubs(subs []types.FleetCategorySub, certType string) []types.ExtractFieldConfig {
	out := make([]types.ExtractFieldConfig, 0, len(subs))
	for _, sub := range subs {
		name := strings.TrimSpace(sub.Name)
		if name == "" || !sub.Enabled {
			continue
		}
		rule := FleetArchiveFieldRule(certType, name)
		label := strings.TrimSpace(sub.Label)
		if label == "" {
			label = name
		}
		desc := rule.Desc
		if desc == "" {
			desc = label
		}
		out = append(out, types.ExtractFieldConfig{
			Name:    name,
			Label:   label,
			Desc:    desc,
			Type:    fleetExtractTypeOf(sub.DataType),
			Rule:    rule.Rule,
			Regex:   rule.Regex,
			Enabled: true,
		})
	}
	return out
}

// fleetExtractTypeOf 把分类字段类型映射成提取字段类型（schema 只认这几种）。
func fleetExtractTypeOf(dataType string) string {
	switch strings.TrimSpace(dataType) {
	case "number":
		return "number"
	case "date":
		return "date"
	case "array":
		return "array"
	case "items":
		return "items"
	case "textarea":
		return "textarea"
	}
	return "string"
}

